use super::*;

/// Render a PipelineReport to a markdown string.
pub fn render_markdown(
    report: &PipelineReport,
    diff_text: Option<&str>,
    elapsed: Duration,
    settings: &Settings,
) -> String {
    // Paper-shaped surveys get title/authors/type headers; custom surveys
    // get a generic header.
    let meta = crate::models::paper_view(&report.orientation).map(|v| v.metadata);
    let mut md = String::new();

    // The report is the document; the reviewed paper is its subject. Keeping
    // those roles distinct avoids presenting the paper title/author block as
    // though it were authored by Pipeline.
    let subject = meta
        .as_ref()
        .map(|m| m.title.trim().to_string())
        .filter(|t| !t.is_empty())
        .unwrap_or_else(|| "Selected input".to_string());
    md.push_str("# Referee Report\n\n");

    let (provider, model, effort) = models_that_ran(report);

    let type_prefix = meta
        .as_ref()
        .map(|m| format!("**Type**: {} · ", m.paper_type))
        .unwrap_or_default();
    md.push_str(RUN_DETAILS_START);
    md.push('\n');
    md.push_str(&format!("**Review subject**: {subject}  \n"));
    if let Some(m) = &meta {
        if !m.authors.is_empty() {
            md.push_str(&format!("**Authors**: {}  \n", m.authors.join(", ")));
        }
    }
    md.push_str(&format!(
        "{}**Reviewed**: {} · `{}`  \n**LLM**: {} · **Model**: {} · **Effort**: {} · **Generated in**: {}  \n*Report generated by Pipeline*\n\n",
        type_prefix, report.report_date, report.paper_hash,
        provider, model, effort, format_duration(elapsed)
    ));
    md.push_str(RUN_DETAILS_END);
    md.push_str("\n\n");

    let quality_status = if report.quality.status.trim().is_empty() {
        if report.failed_steps.is_empty() {
            "done"
        } else {
            "partial"
        }
    } else {
        report.quality.status.as_str()
    };
    let status_label = status_label(&report.quality, quality_status);
    let status_note = status_notes(&report.quality, quality_status)
        .iter()
        .map(|note| format!(" {note}"))
        .collect::<String>();
    md.push_str(&format!(
        "> **Status:** {status_label}.{status_note} Coverage and limitations are reported below.\n\n",
    ));

    // Warning for failed steps
    if !report.failed_steps.is_empty() {
        let labels: Vec<&str> = report
            .failed_steps
            .iter()
            .map(|f| f.step_label.as_str())
            .collect();
        md.push_str(&format!(
            "> **Incomplete report.** The following steps failed and are not reflected below: {}.\n\n",
            labels.join(", ")
        ));
    }

    md.push_str("---\n\n");

    // Consolidated issues — use final_output() which handles both new and
    // legacy formats and never substitutes a parallel analysis for a failed
    // sequential report step.
    let final_text = crate::findings::canonical_findings(report)
        .filter(|findings| {
            !report.products.primary_step_id.is_empty()
                && findings
                    .source_step_id
                    .split('/')
                    .next()
                    .unwrap_or_default()
                    == report.products.primary_step_id
        })
        .map(|findings| crate::findings::render_markdown(&findings))
        .or_else(|| {
            // Only reports from before the quality ledger can open with
            // narration that does not belong in the report.
            report.final_output().map(|text| {
                if report.quality.schema_version == 0 {
                    strip_to_report(text)
                } else {
                    report_body(text)
                }
            })
        })
        .filter(|text| !text.trim().is_empty());
    if let Some(final_text) = final_text {
        md.push_str(&normalize_math_delimiters(&final_text));
        md.push_str("\n\n");
    } else {
        md.push_str("## Final report unavailable\n\n");
        if report.final_output_blocked_by_failed_sequential() {
            md.push_str(
                "The final report step did not return a valid report. Pipeline has not \n\
                 substituted an individual specialist analysis for the missing final report. \n\
                 Successful step outputs and rejected model responses remain preserved with \n\
                 the run for inspection.\n\n",
            );
        } else if report
            .all_outputs()
            .iter()
            .all(|output| output.skipped || output.raw_text.trim().is_empty())
        {
            md.push_str(
                "No completed step returned usable report content. Preserved run artifacts \n\
                 remain available for inspection.\n\n",
            );
        } else {
            md.push_str(
                "Pipeline could not identify usable canonical report content. Individual step \n\
                 outputs remain preserved with the run for inspection.\n\n",
            );
        }
    }

    // Revision diff
    if let Some(diff) = diff_text {
        md.push_str("---\n\n");
        md.push_str("## Revision Diff\n\n");
        md.push_str(&normalize_math_delimiters(&strip_to_report(diff)));
        md.push_str("\n\n");
    }

    render_quality_section(&mut md, report, &status_label);

    // Per-step timing / tokens / cost, when the run recorded any.
    if let Some(summary) = render_run_summary(report, settings) {
        md.push_str(RUN_DETAILS_START);
        md.push('\n');
        md.push_str("---\n\n");
        md.push_str(&summary);
        md.push_str(RUN_DETAILS_END);
        md.push_str("\n\n");
    }

    md.push_str("---\n");
    md
}

/// The provider, model, and effort for the report header, taken from the calls
/// the run recorded rather than from settings: steps can choose their own
/// models, and a usage limit can move a step to another provider.
fn models_that_ran(report: &PipelineReport) -> (String, String, String) {
    let mut providers = std::collections::BTreeSet::new();
    let mut models = std::collections::BTreeSet::new();
    let mut efforts = std::collections::BTreeSet::new();
    for output in report.all_outputs().iter().filter(|output| !output.skipped) {
        let mut record = |provider: &str, model: &str, effort: &str| {
            // Host analyzers record this provider but call no model.
            if provider == "pipeline" || (provider.is_empty() && model.is_empty()) {
                return;
            }
            providers.insert(capitalize(provider));
            models.insert(model.to_string());
            efforts.insert(if effort.is_empty() { "default" } else { effort }.to_string());
        };
        if output.calls.is_empty() {
            record(&output.provider, &output.model, "");
        }
        for call in &output.calls {
            record(&call.provider, &call.model, &call.effort);
        }
    }
    (
        header_value(providers),
        header_value(models),
        header_value(efforts),
    )
}

fn header_value(mut values: std::collections::BTreeSet<String>) -> String {
    values.remove("");
    let mut distinct = values.into_iter();
    match (distinct.next(), distinct.next()) {
        (Some(value), None) => value,
        (Some(_), Some(_)) => "Mixed; see run summary".to_string(),
        _ => "Not recorded".to_string(),
    }
}

fn render_quality_section(md: &mut String, report: &PipelineReport, status_label: &str) {
    let quality = &report.quality;
    md.push_str("---\n\n## Quality and limitations\n\n");
    md.push_str(&format!("**Final status:** {status_label}  \n"));
    if quality.schema_version == 0 {
        md.push_str(
            "This report predates the deterministic quality ledger; only preserved failure metadata is available.\n\n",
        );
        return;
    }

    md.push_str(&format!(
        "**Extraction coverage:** {} input bytes via {}; {} pages, {} blocks, and {} assets recovered.  \n",
        quality.input_bytes,
        safe_inline(&quality.extraction_method),
        quality.recovered_pages,
        quality.recovered_blocks,
        quality.recovered_assets
    ));
    md.push_str(&format!(
        "**Orientation coverage:** {} bytes included; {} omitted.  \n",
        quality.orientation_included_bytes, quality.orientation_omitted_bytes
    ));
    md.push_str(&format!(
        "**Reviewer coverage:** {} completed, {} failed or blocked, {} skipped.  \n",
        quality.completed_steps.len(),
        quality.failed_steps.len(),
        quality.skipped_steps.len()
    ));
    md.push_str(&format!(
        "**Evidence:** {} verified, {} partially verified, {} unverified, {} not checkable; {} manual-review item(s).  \n",
        quality.verified_evidence,
        quality.partially_verified_evidence,
        quality.unverified_evidence,
        quality.not_checkable_evidence,
        quality.manual_review_items
    ));
    md.push_str(&format!(
        "**Schema retries:** {}.  \n",
        quality.schema_retry_events
    ));
    if !quality.requested_capabilities.is_empty() {
        md.push_str(&format!(
            "**Declared capabilities:** {}.  \n",
            safe_join(&quality.requested_capabilities)
        ));
    }
    if !quality.observed_capabilities.is_empty() {
        md.push_str(&format!(
            "**Observed tool classes:** {}.  \n",
            safe_join(&quality.observed_capabilities)
        ));
    }
    if !quality.external_providers.is_empty() {
        md.push_str(&format!(
            "**External providers:** {}.  \n",
            safe_join(&quality.external_providers)
        ));
    }
    md.push_str(&format!(
        "**Reproducibility hash:** `{}`\n\n",
        safe_inline(&quality.reproducibility_hash)
    ));

    if quality.limitations.is_empty() {
        md.push_str("No deterministic limitations were recorded.\n\n");
    } else {
        md.push_str("### Recorded limitations\n\n");
        for limitation in &quality.limitations {
            md.push_str(&format!("- {}\n", safe_inline(limitation)));
        }
        md.push('\n');
    }
}

fn safe_inline(value: &str) -> String {
    value
        .replace(['\r', '\n'], " ")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('|', "\\|")
}

fn safe_join(values: &[String]) -> String {
    values
        .iter()
        .map(|value| safe_inline(value))
        .collect::<Vec<_>>()
        .join(", ")
}

pub(crate) fn capitalize(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        None => String::new(),
        Some(first) => {
            let upper: String = first.to_uppercase().collect();
            let rest: String = chars.collect();
            upper + &rest
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::models::{StepCallRecord, StepOutput};

    fn report(step_outputs: Vec<StepOutput>) -> PipelineReport {
        PipelineReport {
            orientation: serde_json::Value::Null,
            step_outputs,
            failed_steps: Vec::new(),
            products: Default::default(),
            quality: Default::default(),
            referee_reports: Vec::new(),
            editor: None,
            report_date: chrono::Local::now().date_naive(),
            paper_hash: "hash".to_string(),
        }
    }

    fn call(provider: &str, model: &str, effort: &str) -> StepCallRecord {
        StepCallRecord {
            provider: provider.to_string(),
            model: model.to_string(),
            effort: effort.to_string(),
            ..Default::default()
        }
    }

    fn step(calls: Vec<StepCallRecord>) -> StepOutput {
        StepOutput {
            step_id: "review".to_string(),
            raw_text: "Report".to_string(),
            calls,
            ..Default::default()
        }
    }

    fn header_of(report: &PipelineReport) -> String {
        let settings = Settings {
            preferred_provider: "preferred-provider".to_string(),
            ..Default::default()
        };
        let markdown = render_markdown(report, None, Duration::from_secs(1), &settings);
        let line = markdown.lines().find(|line| line.contains("**LLM**"));
        line.unwrap().to_string()
    }

    #[test]
    fn the_header_names_the_provider_that_ran() {
        let header = header_of(&report(vec![step(vec![call(
            "codex",
            "gpt-5.6-sol",
            "high",
        )])]));
        assert!(
            header.contains("**LLM**: Codex · **Model**: gpt-5.6-sol · **Effort**: high"),
            "{header}"
        );
    }

    #[test]
    fn the_header_does_not_summarize_a_mixed_run_as_one_model() {
        let header = header_of(&report(vec![
            step(vec![call("codex", "gpt-5.6-sol", "high")]),
            step(vec![call("claude", "claude-opus-5-5", "high")]),
        ]));
        assert!(
            header.contains("**LLM**: Mixed; see run summary"),
            "{header}"
        );
        assert!(
            header.contains("**Model**: Mixed; see run summary"),
            "{header}"
        );
        assert!(header.contains("**Effort**: high"), "{header}");
    }

    #[test]
    fn the_header_ignores_host_analyzers_and_skipped_steps() {
        let analyzer = StepOutput {
            provider: "pipeline".to_string(),
            model: "replication_static@1".to_string(),
            ..step(Vec::new())
        };
        let skipped = StepOutput {
            skipped: true,
            ..step(vec![call("claude", "claude-opus-5-5", "low")])
        };
        let header = header_of(&report(vec![
            analyzer,
            skipped,
            step(vec![call("codex", "gpt-5.6-sol", "")]),
        ]));
        assert!(
            header.contains("**LLM**: Codex · **Model**: gpt-5.6-sol · **Effort**: default"),
            "{header}"
        );
    }

    #[test]
    fn a_report_without_call_records_does_not_guess_from_settings() {
        let header = header_of(&report(vec![step(Vec::new())]));
        assert!(!header.contains("Preferred-provider"), "{header}");
        assert!(header.contains("**LLM**: Not recorded"), "{header}");
    }
}
