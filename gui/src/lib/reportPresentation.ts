import {
  isPaperOrientation,
  type PipelineReport,
  type RunSummary,
} from "./types";

type CanonicalReportProblem =
  | "failed-final-step"
  | "missing-content"
  | "no-step-output"
  | "apparent-refusal";

const APPARENT_REFUSAL_RE =
  /\bi(?:\s+(?:cannot|can't|am\s+unable\s+to|must\s+refuse\s+to|will\s+not|won't)|'m\s+unable\s+to)\s+(?:comply(?:\s+with\s+(?:this|the)\s+request)?|(?:provide|produce|write|generate|complete)\s+(?:(?:this|the|a)\s+)?(?:requested\s+)?(?:report|review|task|request)|(?:help|assist)\s+with\s+(?:this|that|the\s+request)|follow\s+(?:these|the)\s+instructions)\b/i;

export function reportTitle(
  report: PipelineReport | null,
  summary?: RunSummary | null,
) {
  if (summary?.title) return summary.title;
  if (report && isPaperOrientation(report.orientation)) {
    const title = report.orientation.metadata?.title;
    if (title) return title;
  }
  if (summary?.input_name) return summary.input_name;
  return "Pipeline report";
}

export function splitUnexpectedPreamble(markdown: string, paperTitle = "") {
  let clean = markdown
    .replace(
      /<!-- PIPELINE RUN DETAILS START -->[\s\S]*?<!-- PIPELINE RUN DETAILS END -->\s*/g,
      "",
    )
    .trim();
  const narration: string[] = [];

  const firstHeading = clean.search(/^#\s+\S/m);
  if (firstHeading > 0) {
    narration.push(clean.slice(0, firstHeading).trim());
    clean = clean.slice(firstHeading).trimStart();
  }

  // Older reports predate the run-details markers. Their generated metadata
  // sits between the H1 and the first rule; the workspace now presents these
  // values as structured provenance instead.
  const legacyHeader = clean.match(/^(#\s+[^\n]+\n)([\s\S]*?)(^---\s*$)/m);
  if (
    legacyHeader &&
    /Report generated by Pipeline|\*\*(?:LLM|Reviewed|Model|Type)\*\*/i.test(
      legacyHeader[2],
    )
  ) {
    clean = clean.replace(
      legacyHeader[0],
      `${legacyHeader[1]}\n${legacyHeader[3]}`,
    );
  }

  // Some older model outputs placed tool-use narration after the generated
  // header and immediately before the first H2, occasionally on the same
  // line as that heading.
  const firstSection = clean.indexOf("## ");
  if (firstSection > 0) {
    const beforeSection = clean.slice(0, firstSection);
    const lastRule = beforeSection.lastIndexOf("---");
    if (lastRule >= 0) {
      const candidate = beforeSection.slice(lastRule + 3).trim();
      if (
        candidate &&
        /^(?:I(?:'|’| a| wi|’m|’ll)|Here(?:'|’)s|Let me|The prompt\b)/i.test(
          candidate,
        )
      ) {
        narration.push(candidate);
        clean = `${beforeSection.slice(0, lastRule + 3).trimEnd()}\n\n${clean.slice(firstSection)}`;
      }
    }
  }

  // Run telemetry remains available in the raw report artifact under Sources;
  // keep the primary reading view focused on the substantive report.
  clean = clean.replace(/\n+(?:---\s*\n+)?## Run summary\b[\s\S]*$/i, "");

  // The app header already identifies the paper. Older report artifacts used
  // the paper title and authors as a second document masthead; replace that
  // duplicate identity with the kind of document the reader is opening.
  const firstTitle = clean.match(/^#\s+([^\n]+)\n?/);
  if (
    firstTitle &&
    paperTitle.trim() &&
    firstTitle[1].replace(/[*_`]/g, "").trim() === paperTitle.trim()
  ) {
    clean = clean.replace(firstTitle[0], "# Referee Report\n");
    clean = clean.replace(
      /^(# Referee Report)\s*\n(?:\s*\n)*(?:\*\*Authors\*\*:[^\n]*(?:\n|$))?/i,
      "$1\n\n",
    );
    clean = clean.replace(/^(# Referee Report)\n{3,}/, "$1\n\n");
  }

  return {
    clean: clean.trim(),
    preamble: narration.filter(Boolean).join("\n\n"),
  };
}

/** Remove the in-app document label when the PDF has its own masthead. */
export function reportBodyForPdf(markdown: string): string {
  return markdown
    .replace(/^#\s+(?:Referee|Review|Pipeline)?\s*Report\s*\n+/i, "")
    .replace(/^---\s*\n+/, "")
    .trim();
}

/**
 * Keep the reading surface conservative at the last boundary. The backend
 * rejects these cases for new runs; this also protects old or partially
 * recovered artifacts that predate the report contract.
 */
export function canonicalReportProblem(
  report: PipelineReport | null,
  markdown: string,
): CanonicalReportProblem | null {
  const visible = markdown.trim();
  if (!visible) return "missing-content";

  if (visible.length <= 4_000) {
    const prefix = visible.slice(0, 1_200).replace(/[’‘]/g, "'");
    if (APPARENT_REFUSAL_RE.test(prefix)) return "apparent-refusal";
  }

  if (!report) return null;
  const usableOutputs = (report.step_outputs ?? []).filter(
    (output) => !output.skipped && output.raw_text.trim().length > 0,
  );
  const hasSequentialOutput = usableOutputs.some(
    (output) => output.phase === "sequential",
  );
  const hasFailedFinalStep = (report.failed_steps ?? []).some((failure) => {
    if (failure.phase === "sequential") return true;
    if (failure.phase) return false;
    // Old reports did not persist phase. Restrict the compatibility heuristic
    // to conventional final-step names rather than guessing from every error.
    return /\b(?:synthesi[sz]|consolidat|editor|validat)\w*\b/i.test(
      `${failure.step_id} ${failure.step_label}`,
    );
  });
  if (!hasSequentialOutput && hasFailedFinalStep) return "failed-final-step";
  if (usableOutputs.length === 0) return "no-step-output";
  return null;
}

export function canonicalProblemMessage(
  problem: CanonicalReportProblem,
): string {
  switch (problem) {
    case "failed-final-step":
      return "The final report could not be created. You can still read the individual reviewers’ analyses in Agent reports.";
    case "apparent-refusal":
      return "The model appears to have declined the review. Open Agent reports to read its response.";
    case "no-step-output":
      return "No step produced a usable report. Open Agent reports to see the saved responses.";
    case "missing-content":
      return "The report is empty or unavailable. Check the saved outputs for details.";
  }
}

/** Remove Pipeline's private markdown boundary tokens before presentation. */
export function stripInternalReportMarkers(markdown: string): string {
  return markdown.replace(
    /<!--\s*PIPELINE RUN DETAILS (?:START|END)\s*-->/gi,
    "",
  );
}
